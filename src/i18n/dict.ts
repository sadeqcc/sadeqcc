/** `t('days_late', { n: 3 })` — placeholders are `{name}`. */
export function translate(lang: Lang, key: DictKey, vars?: Record<string, string | number>): string {
  const raw = dict[lang]?.[key] ?? dict.en[key] ?? String(key);
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}
